export function listTemplates() {
  return Object.keys(TEMPLATES).map(id => ({ id, name: id[0].toUpperCase() + id.slice(1) }));
}

export function getTemplate(template='portfolio', framework='react') {
  const id = String(template || 'portfolio').toLowerCase();
  const factory = TEMPLATES[id] || TEMPLATES.portfolio;
  const files = factory().map(file => ({ ...file }));
  // Framework is metadata only for this dependency-free starter; callers can extend it safely.
  return files.map(file => ({ ...file, framework: String(framework || 'react') }));
}
